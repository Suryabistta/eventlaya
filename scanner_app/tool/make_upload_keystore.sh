#!/usr/bin/env bash
#
# Creates the Google Play upload keystore for Eventlaya and the android/key.properties that points at it.
#
# Run it yourself: it asks for the password on the terminal and only writes it into key.properties, which is
# gitignored. Once a build signed with this key is on Play, every update must be signed with it too, so back the
# keystore and password up (password manager + ~/.eventlaya-deploy/), see docs/mobile-release.md.
#
#   ./tool/make_upload_keystore.sh
#
set -euo pipefail

KEYSTORE="${KEYSTORE:-$HOME/eventlaya-upload.jks}"
ALIAS="${ALIAS:-upload}"
PROPS="${PROPS:-$(cd "$(dirname "$0")/.." && pwd)/android/key.properties}"

# The certificate's subject. Nobody sees it (Play identifies the app by the key's fingerprint).
DNAME="CN=Eventlaya, OU=Mobile, O=Eventlaya, L=Dharan, C=NP"

if [[ -e "$KEYSTORE" ]]; then
  echo "A keystore already exists at $KEYSTORE."
  echo "Refusing to overwrite it: if it is the one Play knows, replacing it would stop this app's updates."
  exit 1
fi

echo "Creating the upload keystore for com.eventlaya.eventlaya_scanner"
echo
echo "Choose a strong password and save it in your password manager NOW, before you type it."
echo "It cannot be recovered from the keystore."
echo

read -r -s -p "Keystore password: " PASS
echo
read -r -s -p "Type it again: " PASS_CONFIRM
echo

if [[ "$PASS" != "$PASS_CONFIRM" ]]; then
  echo "Those do not match. Nothing was created."
  exit 1
fi
if [[ ${#PASS} -lt 12 ]]; then
  echo "Use at least 12 characters. Nothing was created."
  exit 1
fi

# The password goes in through the environment, not the command line (shell history, process list).
KS_PASS="$PASS" keytool -genkeypair \
  -keystore "$KEYSTORE" \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize 2048 \
  -validity 10000 \
  -dname "$DNAME" \
  -storetype PKCS12 \
  -storepass:env KS_PASS \
  -keypass:env KS_PASS

chmod 600 "$KEYSTORE"

umask 077
cat > "$PROPS" <<PROPERTIES
# Generated by tool/make_upload_keystore.sh. Gitignored: never commit this.
storePassword=$PASS
keyPassword=$PASS
keyAlias=$ALIAS
storeFile=$KEYSTORE
PROPERTIES
chmod 600 "$PROPS"

echo
echo "Created:"
echo "  $KEYSTORE"
echo "  $PROPS"
echo
echo "Fingerprints. Add the SHA-1 to Firebase (Project settings → Android app) so Google sign-in works in"
echo "release builds; keep the SHA-256 for App Links:"
echo
KS_PASS="$PASS" keytool -list -v -keystore "$KEYSTORE" -alias "$ALIAS" -storepass:env KS_PASS 2>/dev/null | grep -E "SHA1:|SHA256:"
echo
echo "Now back it up: copy $KEYSTORE to ~/.eventlaya-deploy/ and keep the password in your password manager."
