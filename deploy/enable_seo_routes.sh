#!/usr/bin/env bash
# SEO routes in the live Nginx site (run as root; safe to re-run). docs/seo.md explains the whole set-up.
#
# Adds one managed block ("# BEGIN eventlaya-seo" … "# END eventlaya-seo") to every server block that serves the
# web app (`root /srv/eventlaya/frontend;`):
#   • all of them (eventlaya.com and the white-label default server): /robots.txt, /sitemap.xml, /sitemaps/*,
#     /llms.txt, /llms-full.txt and the pages with server-rendered metadata (/e/…, /blog…, /marketplace/venues|vendors/…)
#     go to Django (apps/seo); if Django is down those pages fall back to the plain app shell.
#   • eventlaya.com only (not default_server): the prerendered marketing pages in /srv/eventlaya/frontend/prerender/
#     for /events, /marketplace, /pricing and the legal pages; / goes through Django, which serves its prerendered
#     copy with the search-engine verification tags (falls back to the static copy if Django is down).
#     White-label hosts never get them.
#
# The live file was rewritten by certbot (listen 443 ssl + redirect blocks), so it is patched in place, never
# re-rendered from deploy/nginx.conf. Certbot's redirect-only blocks have no `root`, so they are left alone.
# The managed block is replaced on every run (so changes here reach the server), a backup is kept, and the backup
# is restored if `nginx -t` fails.
#
#   SITE=/path/to/site deploy/enable_seo_routes.sh     # another file
#   NGINX_RELOAD=0 deploy/enable_seo_routes.sh        # patch only (no nginx -t / reload), e.g. to test on a copy
set -euo pipefail

SITE=${SITE:-/etc/nginx/sites-available/eventlaya}
NGINX_RELOAD=${NGINX_RELOAD:-1}

if [ ! -f "$SITE" ]; then
  echo "WARNING: $SITE not found; skipped the SEO routes" >&2
  exit 0
fi

BACKUP="$SITE.bak-seo-$(date +%Y%m%d%H%M%S)-$$"
cp "$SITE" "$BACKUP"

python3 - "$SITE" <<'PY'
import re
import sys

path = sys.argv[1]
text = open(path).read()
BEGIN, END = '# BEGIN eventlaya-seo', '# END eventlaya-seo'

DJANGO = '''        proxy_pass http://eventlaya_api;
        include /etc/nginx/proxy_params;'''

COMMON = f'''    {BEGIN} (managed by deploy/enable_seo_routes.sh; edits inside are overwritten)
    # robots.txt, sitemaps and llms.txt are generated by Django (apps/seo) for each host.
    location = /robots.txt {{
{DJANGO}
    }}
    location = /sitemap.xml {{
{DJANGO}
    }}
    location ^~ /sitemaps/ {{
{DJANGO}
    }}
    location = /llms.txt {{
{DJANGO}
    }}
    location = /llms-full.txt {{
{DJANGO}
    }}
    # Pages whose HTML carries their own title, description, canonical, Open Graph and JSON-LD (apps/seo).
    # If the app server is down, visitors still get the web app.
    location ~ ^/(e/|blog(/|$)|marketplace/(venues|vendors)/) {{
{DJANGO}
        proxy_intercept_errors on;
        error_page 502 503 504 = @eventlaya_spa;
    }}
    location @eventlaya_spa {{
        try_files /index.html =404;
    }}
    location ^~ /prerender/ {{
        internal;
    }}
'''

PLATFORM = '''    # Prerendered marketing pages (npm run prerender → /srv/eventlaya/frontend/prerender/), eventlaya.com only.
    # The homepage goes through Django (apps/seo): it serves the same prerendered copy plus the Search Console /
    # Bing verification tags saved in Admin → Analytics. Django down → the static copy.
    location = / {
{DJANGO}
        proxy_intercept_errors on;
        error_page 502 503 504 = @eventlaya_home;
    }
    location @eventlaya_home {
        try_files /prerender/index.html /index.html =404;
    }
    location ~ ^/(events|marketplace|pricing|privacy|terms|community-guidelines|delete-account|contact)/?$ {
        try_files /prerender/$1/index.html /index.html;
    }
'''.replace('{DJANGO}', DJANGO)


def server_blocks(s):
    """(start, end) of each top-level `server { ... }` block (end = index of its closing brace)."""
    out, i = [], 0
    for m in re.finditer(r'(?m)^\s*server\s*\{', s):
        if m.start() < i:
            continue
        depth, j = 0, m.end() - 1
        while j < len(s):
            if s[j] == '{':
                depth += 1
            elif s[j] == '}':
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append((m.start(), j))
        i = j
    return out


managed = re.compile(r'[ \t]*' + re.escape(BEGIN) + r'.*?' + re.escape(END) + r'[^\n]*\n', re.S)
platform = tenant = 0
for start, end in reversed(server_blocks(text)):
    block = text[start:end]
    if not re.search(r'(?m)^\s*root\s+/srv/eventlaya/frontend\s*;', block):
        continue  # API server, certbot redirect blocks
    is_default = bool(re.search(r'(?m)^\s*listen\s[^;]*\bdefault_server\b', block))
    block = managed.sub('', block)
    snippet = COMMON + ('' if is_default else PLATFORM) + f'    {END}\n'
    first_location = re.search(r'(?m)^[ \t]*location\s', block)
    at = first_location.start() if first_location else len(block)
    block = block[:at] + snippet + block[at:]
    text = text[:start] + block + text[end:]
    if is_default:
        tenant += 1
    else:
        platform += 1

open(path, 'w').write(text)
print(f'nginx: SEO routes in {platform} eventlaya.com server block(s) and {tenant} white-label block(s)')
PY

if cmp -s "$SITE" "$BACKUP"; then
  rm -f "$BACKUP"
  echo "Nginx SEO routes already up to date."
elif [ "$NGINX_RELOAD" != 1 ]; then
  echo "Patched $SITE (backup: $BACKUP); not testing/reloading (NGINX_RELOAD=$NGINX_RELOAD)."
elif nginx -t; then
  systemctl reload nginx
  echo "Nginx reloaded with the SEO routes (backup: $BACKUP)"
else
  echo "nginx -t failed; restoring $BACKUP" >&2
  cp "$BACKUP" "$SITE"
  exit 1
fi
